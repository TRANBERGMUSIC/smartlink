const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('laser', {
  sendDmx: (universe, ip, data) => ipcRenderer.send('dmx', { universe, ip, data }),
  stats: () => ipcRenderer.invoke('stats'),
  micAccess: () => ipcRenderer.invoke('mic-access'),
  saveShow: (name, json) => ipcRenderer.invoke('save-show', { name, json }),
  openShow: () => ipcRenderer.invoke('open-show'),
  pickAudio: () => ipcRenderer.invoke('pick-audio'),
  readAudio: (p) => ipcRenderer.invoke('read-audio', p),
  saveIldBatch: (title, files) => ipcRenderer.invoke('save-ild-batch', { title, files }),
  saveIld: (name, bytes, alsoLocal) => ipcRenderer.invoke('save-ild', { name, bytes, alsoLocal }),
  patImport: () => ipcRenderer.invoke('pat-import'),
  patList: () => ipcRenderer.invoke('pat-list'),
  patRead: (n) => ipcRenderer.invoke('pat-read', n),
  patDelete: (n) => ipcRenderer.invoke('pat-delete', n),
  patClear: () => ipcRenderer.invoke('pat-clear'),
  remoteInfo: () => ipcRenderer.invoke('remote-info'),
  remoteEnable: (on) => ipcRenderer.invoke('remote-enable', on),
  remoteNewKey: () => ipcRenderer.invoke('remote-newkey'),
  remoteState: (json) => ipcRenderer.send('remote-state', json),
  camAccess: () => ipcRenderer.invoke('cam-access'),
  usbDiag: () => ipcRenderer.invoke('usb-diag'),
  stateDump: (txt) => ipcRenderer.send('state-dump', txt),
  profileSave: (txt) => ipcRenderer.invoke('profile-save', txt),
  onCamFrame: (fn) => ipcRenderer.on('cam-frame', (_e, d) => fn(d)),
  onUsbList: (fn) => ipcRenderer.on('usb-list', (_e, d) => fn(d)),
  onDmxIn: (fn) => ipcRenderer.on('dmx-in', (_e, d) => fn(d)),
  onRemoteCmd: (fn) => ipcRenderer.on('remote-cmd', (_e, c) => fn(c)),
  onRemoteCount: (fn) => ipcRenderer.on('remote-count', (_e, n) => fn(n)),
  reconnect: () => ipcRenderer.invoke('reconnect'),
  appVersion: () => ipcRenderer.invoke('app-version'),
  updateCheck: () => ipcRenderer.invoke('update-check'),
  updateInstall: (url) => ipcRenderer.invoke('update-install', url),
  onUpdateProgress: (fn) => ipcRenderer.on('update-progress', (_e, p) => fn(p)),
  netStatus: (ip) => ipcRenderer.invoke('net-status', ip),
  netSetup: (ip) => ipcRenderer.invoke('net-setup', ip),
  pollTarget: (ip) => ipcRenderer.send('poll-target', ip),
  outDiscover: (id) => ipcRenderer.invoke('out-discover', id),
  outOpen: (id, opts) => ipcRenderer.invoke('out-open', { id, opts }),
  outFrame: (points, pps) => ipcRenderer.send('out-frame', { points, pps }),
  outShutter: (open) => ipcRenderer.send('out-shutter', open),
  outClose: () => ipcRenderer.invoke('out-close'),
  onOutStatus: (fn) => ipcRenderer.on('out-status', (_e, s) => fn(s)),
  saveSdPackage: (title, files, table) => ipcRenderer.invoke('save-sd-package', { title, files, table }),
  wolfMonitorImport: () => ipcRenderer.invoke('wolfmon-import'),
  netRemove: () => ipcRenderer.invoke('net-remove'),
});
